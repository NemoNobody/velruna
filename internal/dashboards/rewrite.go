package dashboards

import (
	"bufio"
	"bytes"
	"encoding/json"
	"fmt"
)

// RewriteFields replaces the "fields" attribute (a JSON string) of the
// index-pattern objects whose title appears in fieldsByTitle. Every other
// byte of the bundle is preserved: lines that are not touched are copied
// verbatim, and a touched line is re-encoded token by token, keeping the key
// order and the ", " / ": " spacing the bundle was generated with. A generator
// that reformatted the whole file would turn a mapping change into a diff no
// reviewer can read.
func RewriteFields(bundle []byte, fieldsByTitle map[string]string) ([]byte, error) {
	if len(fieldsByTitle) == 0 {
		return bundle, nil
	}
	var out bytes.Buffer
	sc := bufio.NewScanner(bytes.NewReader(bundle))
	sc.Buffer(make([]byte, 0, 64*1024), 8*1024*1024)
	line := 0
	sawContent := false
	for sc.Scan() {
		line++
		raw := sc.Bytes()
		trimmed := bytes.TrimSpace(raw)
		if len(trimmed) == 0 {
			// Keep interior blank lines (a single O(1) flag, not a rescan of
			// the output so far); only leading blanks are dropped.
			if sawContent {
				out.WriteByte('\n')
			}
			continue
		}
		sawContent = true
		replacement, title, err := targetFields(trimmed, fieldsByTitle)
		if err != nil {
			return nil, fmt.Errorf("bundle line %d: %w", line, err)
		}
		if replacement == nil {
			out.Write(raw)
			out.WriteByte('\n')
			continue
		}
		dec := json.NewDecoder(bytes.NewReader(trimmed))
		dec.UseNumber()
		rewritten, err := copyValue(nil, dec, "", func(path string) *string {
			if path == "attributes.fields" {
				return replacement
			}
			return nil
		})
		if err != nil {
			return nil, fmt.Errorf("bundle line %d (%s): %w", line, title, err)
		}
		if !json.Valid(rewritten) {
			return nil, fmt.Errorf("bundle line %d (%s): rewrite is not valid JSON", line, title)
		}
		out.Write(rewritten)
		out.WriteByte('\n')
	}
	if err := sc.Err(); err != nil {
		return nil, fmt.Errorf("read bundle: %w", err)
	}
	return out.Bytes(), nil
}

// targetFields reports the replacement fields string for one bundle line, or
// nil when the line is not a targeted index pattern.
func targetFields(line []byte, fieldsByTitle map[string]string) (*string, string, error) {
	var probe struct {
		Type       string `json:"type"`
		Attributes struct {
			Title  string          `json:"title"`
			Fields json.RawMessage `json:"fields"`
		} `json:"attributes"`
	}
	if err := json.Unmarshal(line, &probe); err != nil {
		return nil, "", err
	}
	if probe.Type != "index-pattern" {
		return nil, "", nil
	}
	repl, ok := fieldsByTitle[probe.Attributes.Title]
	if !ok {
		return nil, "", nil
	}
	if len(probe.Attributes.Fields) == 0 {
		// Inserting a key would change the object's shape; the generator has
		// always written this key, so its absence means the bundle is not the
		// one this tool produced.
		return nil, probe.Attributes.Title, fmt.Errorf(
			"index pattern %q has no attributes.fields: the bundle was not generated by velruna",
			probe.Attributes.Title)
	}
	return &repl, probe.Attributes.Title, nil
}

// copyValue copies one JSON value from dec to dst, rendering it with the
// bundle's spacing. replaceAt is consulted for every object key with its
// dotted path: returning a non-nil string substitutes that value (the original
// is still consumed from the decoder).
func copyValue(dst []byte, dec *json.Decoder, path string, replaceAt func(string) *string) ([]byte, error) {
	tok, err := dec.Token()
	if err != nil {
		return nil, err
	}
	switch t := tok.(type) {
	case json.Delim:
		switch t {
		case '{':
			dst = append(dst, '{')
			first := true
			for dec.More() {
				kt, err := dec.Token()
				if err != nil {
					return nil, err
				}
				key, ok := kt.(string)
				if !ok {
					return nil, fmt.Errorf("object key is not a string")
				}
				if !first {
					dst = append(dst, ',', ' ')
				}
				first = false
				dst = append(dst, jsonString(key)...)
				dst = append(dst, ':', ' ')
				child := key
				if path != "" {
					child = path + "." + key
				}
				if rep := replaceAt(child); rep != nil {
					dst = append(dst, jsonString(*rep)...)
					var skip json.RawMessage
					if err := dec.Decode(&skip); err != nil {
						return nil, err
					}
					continue
				}
				dst, err = copyValue(dst, dec, child, replaceAt)
				if err != nil {
					return nil, err
				}
			}
			if _, err := dec.Token(); err != nil { // the closing '}'
				return nil, err
			}
			return append(dst, '}'), nil
		case '[':
			dst = append(dst, '[')
			first := true
			for dec.More() {
				if !first {
					dst = append(dst, ',', ' ')
				}
				first = false
				dst, err = copyValue(dst, dec, path, replaceAt)
				if err != nil {
					return nil, err
				}
			}
			if _, err := dec.Token(); err != nil { // the closing ']'
				return nil, err
			}
			return append(dst, ']'), nil
		default:
			return nil, fmt.Errorf("unexpected delimiter %v", t)
		}
	case string:
		return append(dst, jsonString(t)...), nil
	case json.Number:
		return append(dst, string(t)...), nil
	case bool:
		return append(dst, jsonBool(t)...), nil
	case nil:
		return append(dst, "null"...), nil
	default:
		return nil, fmt.Errorf("unexpected token %T", tok)
	}
}
